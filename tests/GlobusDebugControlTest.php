	public function testIsMuDropinInstalledCachesResultWithinRequest(): void {
		$this->plugin()->install_mu_dropin();

		// Simulate a fresh filesystem layer for each check.
		$GLOBALS['wp_filesystem'] = null;
		$base                     = $GLOBALS['gdc_test_state']['wp_filesystem_calls'];

		$this->assertTrue($this->plugin()->is_mu_dropin_installed());
		$GLOBALS['wp_filesystem'] = null;

		$this->assertTrue($this->plugin()->is_mu_dropin_installed());
		$this->assertSame($base + 1, $GLOBALS['gdc_test_state']['wp_filesystem_calls']);
	}

