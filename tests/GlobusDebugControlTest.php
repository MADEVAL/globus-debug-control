<?php
declare(strict_types=1);

namespace GDC\Tests;

final class GlobusDebugControlTest extends WordPressTestCase {
	public function testGetOptionsMigratesLegacyOptionsAndNormalizesValues(): void {
		$options = $this->setLegacyOnlyOptions([
			'enabled' => '1',
			'suppress_notices' => '',
			'suppress_deprecated' => '1',
			'suppress_warnings' => '1',
			'display_errors_mode' => 'broken',
			'log_path' => " logs/debug.log \n",
			'log_max_size_mb' => 999,
		]);

		$this->assertSame(1, $options['enabled']);
		$this->assertSame(0, $options['suppress_notices']);
		$this->assertSame(1, $options['suppress_warnings']);
		$this->assertSame('inherit', $options['display_errors_mode']);
		$this->assertSame('logs/debug.log', $options['log_path']);
		$this->assertSame(100, $options['log_max_size_mb']);
		$this->assertSame([
			'enabled' => '1',
			'suppress_notices' => '',
			'suppress_deprecated' => '1',
			'suppress_warnings' => '1',
			'display_errors_mode' => 'broken',
			'log_path' => " logs/debug.log \n",
			'log_max_size_mb' => 999,
		], $this->state('updated_options')['globus_debug_control_options']);
		$this->assertContains('gdc_options', $this->state('deleted_options'));
	}

	public function testBuildSuppressMaskIncludesSelectedErrorTypes(): void {
		$mask = $this->invokePrivate('build_suppress_mask', [[
			'suppress_deprecated' => 1,
			'suppress_notices' => 1,
			'suppress_warnings' => 1,
			'suppress_strict' => 1,
		]]);

		$this->assertSame(E_DEPRECATED, $mask & E_DEPRECATED);
		$this->assertSame(E_USER_DEPRECATED, $mask & E_USER_DEPRECATED);
		$this->assertSame(E_NOTICE, $mask & E_NOTICE);
		$this->assertSame(E_USER_NOTICE, $mask & E_USER_NOTICE);
		$this->assertSame(E_WARNING, $mask & E_WARNING);
		$this->assertSame(E_USER_WARNING, $mask & E_USER_WARNING);

		if (version_compare(PHP_VERSION, '8.0.0', '<') && defined('E_STRICT')) {
			$this->assertSame(E_STRICT, $mask & E_STRICT);
		}
	}

	public function testResolveLogPathConvertsRelativePathIntoWpContentPath(): void {
		$path = $this->invokePrivate('resolve_log_path', [[
			'log_path' => 'logs/debug.log',
		]]);

		$this->assertSame(str_replace('\\', '/', WP_CONTENT_DIR . '/logs/debug.log'), $path);
	}

	public function testSanitizeOptionsClampsValuesAndSanitizesText(): void {
		$options = $this->plugin()->sanitize_options([
			'enabled' => '1',
			'log_enabled' => '1',
			'display_errors_mode' => 'invalid-mode',
			'log_path' => " custom/debug.log\n",
			'log_max_size_mb' => 500,
		]);

		$this->assertSame(1, $options['enabled']);
		$this->assertSame(1, $options['log_enabled']);
		$this->assertSame('inherit', $options['display_errors_mode']);
		$this->assertSame('custom/debug.log', $options['log_path']);
		$this->assertSame(100, $options['log_max_size_mb']);
		$this->assertSame(0, $options['install_mu_dropin']);
	}

	public function testFilterBodyClassRemovesPhpErrorWhenFeatureEnabled(): void {
		$this->refreshOptions([
			'enabled' => 1,
			'remove_php_error_bodyclass' => 1,
		]);

		$classes = $this->plugin()->filter_body_class(['home', 'php-error', 'page']);

		$this->assertSame(['home', 'page'], $classes);
	}

	public function testFilterAdminBodyClassKeepsClassesWhenFeatureDisabled(): void {
		$this->refreshOptions([
			'enabled' => 1,
			'remove_php_error_bodyclass' => 0,
		]);

		$classes = $this->plugin()->filter_admin_body_class('wp-admin php-error branch-6-9');

		$this->assertSame('wp-admin php-error branch-6-9', $classes);
	}

	public function testPluginActionLinksPrependsSettingsLink(): void {
		$links = $this->plugin()->plugin_action_links(['Existing']);

		$this->assertStringContainsString('options-general.php?page=globus-debug-control', $links[0]);
		$this->assertSame('Existing', $links[1]);
	}

	public function testGenerateMuContentIncludesMigrationAndVersionInfo(): void {
		$content = $this->invokePrivate('generate_mu_content');

		$this->assertStringContainsString('Auto-generated by GLOBUS Debug Control v2.2.4', $content);
		$this->assertStringContainsString("get_option( 'globus_debug_control_options'", $content);
		$this->assertStringContainsString("delete_option( 'gdc_options' )", $content);
		$this->assertStringContainsString("add_filter( 'enable_wp_debug_mode_checks', '__return_false', 1 );", $content);
	}

	public function testInstallAndRemoveMuDropinManageOwnedFile(): void {
		$path = str_replace('\\', '/', WPMU_PLUGIN_DIR . '/gdc-early-loader.php');

		$this->assertTrue($this->plugin()->install_mu_dropin());
		$this->assertFileExists($path);
		$this->assertStringContainsString('GLOBUS Debug Control - Early Loader', (string) file_get_contents($path));

		$this->assertTrue($this->plugin()->remove_mu_dropin());
		$this->assertFileDoesNotExist($path);
		$this->assertContains($path, array_map(static fn ($file) => str_replace('\\', '/', $file), $this->state('deleted_files')));
	}

	public function testInstallMuDropinDoesNotOverwriteForeignFile(): void {
		$path = WPMU_PLUGIN_DIR . '/gdc-early-loader.php';
		file_put_contents($path, "<?php\n// foreign dropin\n");

		$this->assertFalse($this->plugin()->install_mu_dropin());
		$this->assertSame("<?php\n// foreign dropin\n", (string) file_get_contents($path));
	}

	public function testIsApiContextDetectsHeartbeatRequest(): void {
		$_POST['action'] = 'heartbeat';

		$this->assertTrue($this->invokePrivate('is_api_context'));
	}
}