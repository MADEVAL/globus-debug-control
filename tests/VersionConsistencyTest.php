<?php
declare(strict_types=1);

namespace GDC\Tests;

final class VersionConsistencyTest extends WordPressTestCase {
	private function pluginVersion(): string {
		$reflection = new \ReflectionClass(\Globus_Debug_Control::class);
		return (string) $reflection->getReflectionConstant('VERSION')->getValue();
	}

	private function pluginHeader(): string {
		return (string) file_get_contents(dirname(__DIR__) . '/globus-debug-control/globus-debug-control.php');
	}

	private function readme(): string {
		return (string) file_get_contents(dirname(__DIR__) . '/globus-debug-control/readme.txt');
	}

	private function extractHeaderValue(string $header, string $source): string {
		if (preg_match('/^[ \t]*(?:\*[ \t]*)?' . preg_quote($header, '/') . ':[ \t]*(.+)$/m', $source, $match)) {
			return trim($match[1]);
		}
		return '';
	}

	public function testPluginHeaderVersionMatchesClassConstant(): void {
		$this->assertSame(
			$this->pluginVersion(),
			$this->extractHeaderValue('Version', $this->pluginHeader())
		);
	}

	public function testReadmeStableTagMatchesPluginVersion(): void {
		$this->assertSame(
			$this->pluginVersion(),
			$this->extractHeaderValue('Stable tag', $this->readme())
		);
	}

	public function testReadmeTestedUpToMatchesPluginHeader(): void {
		$this->assertSame(
			$this->extractHeaderValue('Tested up to', $this->pluginHeader()),
			$this->extractHeaderValue('Tested up to', $this->readme())
		);
	}

	public function testMuDropinContentUsesCurrentVersion(): void {
		$reflection = new \ReflectionClass(\Globus_Debug_Control::class);
		$method     = $reflection->getMethod('generate_mu_content');
		$content    = $method->invoke($this->plugin());

		$this->assertStringContainsString(
			'Auto-generated by GLOBUS Debug Control v' . $this->pluginVersion(),
			$content
		);
	}
}
